import pandas as pd

print("=== INÍCIO DA ANÁLISE EXPLORATÓRIA DE DADOS (VAREJO) ===\n")

# SPRINT 1: Importação e Inspeção Inicial
df = pd.read_csv("Base Varejo.csv", sep=";", encoding="latin1")
df = df.loc[:, ~df.columns.str.contains('^Unnamed')]

print("--- 1. INFORMAÇÕES INICIAIS DA BASE ---")
print(f"Número total de registros (linhas) e colunas: {df.shape}")
print("\nTipos de dados de cada coluna:")
print(df.dtypes)

# SPRINT 2 & 3: Tratamento de Nulos e Duplicadas
df = df.drop_duplicates()
if "PR_CAT" in df.columns:
    df["PR_CAT"] = df["PR_CAT"].fillna("Sem Categoria")
if "DATA" in df.columns:
    df["DATA"] = pd.to_datetime(df["DATA"], format="%d/%m/%Y", errors="coerce")
    print("\nColuna 'DATA' convertida com sucesso para datetime!")

# SPRINT 4: Estatística Descritiva (Número de Filhos - CL_FHL)
print("\n--- 4. ESTATÍSTICA DESCRITIVA (CL_FHL - Número de Filhos) ---")
coluna_filhos = "CL_FHL"
if coluna_filhos in df.columns:
    print(f"Média: {df[coluna_filhos].mean():.2f}")
    print(f"Mediana: {df[coluna_filhos].median()}")
    print(f"Desvio Padrão: {df[coluna_filhos].std():.2f}")
    print(f"Moda: {df[coluna_filhos].mode()[0]}")
    print(f"Máximo: {df[coluna_filhos].max()}")
    print(f"Mínimo: {df[coluna_filhos].min()}")
    print(f"Contagem: {df[coluna_filhos].count()}")

# SPRINT 5: Padrões de Agrupamento
print("\n--- 5. PADRÕES DE AGRUPAMENTO ---")
if "PR_CAT" in df.columns and "CO_ID" in df.columns:
    vendas_cat = df.groupby("PR_CAT")["CO_ID"].count().reset_index(name="Total_Compras")
    print("Vendas por Categoria de Produto:")
    print(vendas_cat.sort_values(by="Total_Compras", ascending=False))

if "CL_GENERO" in df.columns:
    vendas_gen = df.groupby("CL_GENERO")["CO_ID"].count().reset_index(name="Total_Compras")
    print("\nVendas por Gênero:")
    print(vendas_gen)

# Exportando a base limpa
df.to_csv("df_limpo_varejo.csv", index=False)
print("\nArquivo 'df_limpo_varejo.csv' gerado e salvo com sucesso na sessão do Colab!")